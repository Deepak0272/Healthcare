const nodemailer = require('nodemailer');

const hasSmtpConfigured = () => {
  return (
    process.env.SMTP_HOST &&
    process.env.SMTP_USER &&
    process.env.SMTP_PASS &&
    process.env.SMTP_HOST !== 'smtp.example.com'
  );
};

const sendEmail = async ({ to, subject, html, text }) => {
  if (hasSmtpConfigured()) {
    const transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: process.env.SMTP_PORT || 587,
      secure: process.env.SMTP_SECURE === 'true',
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS
      }
    });

    const info = await transporter.sendMail({
      from: `"Health Tech Alerts" <${process.env.SMTP_FROM || 'alerts@healthtech.local'}>`,
      to,
      subject,
      text,
      html
    });

    return {
      success: true,
      mode: 'live_email',
      messageId: info.messageId
    };
  } else {
    // Elegant, interactive Demo Simulation Mode
    console.log(`[Notification Service - DEMO MODE] Simulated Email Dispatch`);
    console.log(`To: ${to} | Subject: ${subject}`);
    console.log(`Body preview: ${text ? text.slice(0, 100) : 'HTML message'}`);
    return {
      success: true,
      mode: 'demo_simulation',
      simulatedRecipient: to,
      timestamp: new Date().toISOString()
    };
  }
};

const dispatchEmergencyAlert = async (patient, contacts, alertDetails) => {
  const notifications = [];
  const isDemo = !hasSmtpConfigured();

  for (const contact of contacts) {
    const emailSubject = `[URGENT] Health Tech Emergency Assistance: ${patient.name}`;
    const emailBody = `
HEALTH TECH - EMERGENCY ASSISTANCE ALERT (DEMO SIMULATION / NOTIFICATION)
========================================================================
Patient Name: ${patient.name}
Contact Number: ${patient.phone || 'Not provided'}
Triggered At: ${new Date().toLocaleString()}
Alert Reason: ${alertDetails.reason || 'Patient pressed Emergency SOS button'}
Location Notes: ${alertDetails.locationNotes || 'Registered Patient Residence'}

Configured Emergency Contact: ${contact.name} (${contact.relationship})
Phone: ${contact.phoneNumber}
Email: ${contact.email}

NOTICE: This alert was generated by the Health Tech platform. If this is an actual life-threatening medical emergency, please dial 911 or your local emergency first responder service directly.
========================================================================
    `;

    try {
      const result = await sendEmail({
        to: contact.email,
        subject: emailSubject,
        text: emailBody
      });

      notifications.push({
        contactId: contact._id,
        name: contact.name,
        phone: contact.phoneNumber,
        email: contact.email,
        deliveryStatus: isDemo ? 'Demo Simulated' : 'Sent',
        deliveryChannel: isDemo ? 'Demo Simulation (Email/SMS)' : 'SMTP Live Email',
        sentAt: new Date(),
        details: isDemo
          ? 'Demo Notification Mode: Successfully simulated SMS and Email broadcast to contact.'
          : 'Live email delivered to emergency contact.'
      });
    } catch (err) {
      notifications.push({
        contactId: contact._id,
        name: contact.name,
        phone: contact.phoneNumber,
        email: contact.email,
        deliveryStatus: 'Failed',
        deliveryChannel: isDemo ? 'Demo Simulation' : 'Live Email',
        sentAt: new Date(),
        details: `Delivery failure: ${err.message}`
      });
    }
  }

  return {
    isDemoMode: isDemo,
    notifications
  };
};

module.exports = {
  sendEmail,
  dispatchEmergencyAlert,
  hasSmtpConfigured
};
